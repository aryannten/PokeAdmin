export const GEN3_EOS = 0xFF;
export const GEN3_SPACE = 0x00;

/**
 * Decode a Gen 3 byte array into a human-readable JavaScript string.
 * Stops at terminator 0xFF or buffer length.
 */
export function decodeGen3String(bytes: Uint8Array | number[]): string {
  let result = '';
  for (let i = 0; i < bytes.length; i++) {
    const b = bytes[i];
    if (b === GEN3_EOS) {
      break;
    }
    if (b === GEN3_SPACE) {
      result += ' ';
    } else if (GEN3_BYTE_TO_CHAR[b] !== undefined) {
      result += GEN3_BYTE_TO_CHAR[b];
    } else {
      // Fallback for unmapped byte
      result += '?';
    }
  }
  return result;
}

/**
 * Encode a JavaScript string into a Gen 3 byte array padded to fixed length.
 * Appends 0xFF (EOS) after string and pads remainder with 0xFF.
 */
export function encodeGen3String(text: string, length: number): Uint8Array {
  const result = new Uint8Array(length);
  result.fill(GEN3_EOS);

  let outIdx = 0;
  for (let i = 0; i < text.length && outIdx < length; i++) {
    const ch = text[i];
    if (ch === ' ') {
      result[outIdx++] = GEN3_SPACE;
    } else if (GEN3_CHAR_TO_BYTE[ch] !== undefined) {
      result[outIdx++] = GEN3_CHAR_TO_BYTE[ch];
    } else {
      // Unmapped character: attempt ASCII uppercase or lowercase
      const upper = ch.toUpperCase();
      if (GEN3_CHAR_TO_BYTE[upper] !== undefined) {
        result[outIdx++] = GEN3_CHAR_TO_BYTE[upper];
      } else {
        result[outIdx++] = GEN3_CHAR_TO_BYTE['?'] ?? 0xAC;
      }
    }
  }

  // If there is room left, ensure EOS is present at termination
  if (outIdx < length) {
    result[outIdx] = GEN3_EOS;
  }

  return result;
}
